#!/usr/bin/env bash
# Local Johnny demo: a real single-node Garage cluster, realistic sample data and the web panel.
#
#   bash demo/up.sh            # start (idempotent; data is kept between runs)
#   bash demo/down.sh [--wipe] # stop (and optionally delete demo/.state)
#
# Requirements: garage 2.x in PATH (macOS: `brew install garage`), PHP 8.5 + Composer, curl, openssl.
# Nothing is installed system-wide: Garage, its data and the panel database live in demo/.state/.
set -euo pipefail

DEMO_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$DEMO_DIR/.." && pwd)"
PANEL_DIR="$REPO_ROOT/panel"

# shellcheck source=demo/lib.sh
source "$DEMO_DIR/lib.sh"

command -v "$GARAGE_BIN" >/dev/null || die "garage not found (set GARAGE_BIN or install it: brew install garage)."
command -v php >/dev/null || die "php not found."
command -v composer >/dev/null || die "composer not found."

mkdir -p "$STATE/meta" "$STATE/data" "$STATE/bin" "$STATE/credentials" "$STATE/logs"

# --- Garage -----------------------------------------------------------------
if [[ ! -f "$STATE/garage.toml" ]]; then
  log "Writing Garage config"
  cat >"$STATE/garage.toml" <<EOF
metadata_dir = "$STATE/meta"
data_dir = "$STATE/data"
db_engine = "sqlite"
replication_factor = 1

rpc_bind_addr = "127.0.0.1:$RPC_PORT"
rpc_public_addr = "127.0.0.1:$RPC_PORT"
rpc_secret = "$(openssl rand -hex 32)"

[s3_api]
s3_region = "johnny"
api_bind_addr = "127.0.0.1:$S3_PORT"
root_domain = ".s3.localhost"

[admin]
api_bind_addr = "127.0.0.1:$ADMIN_PORT"
admin_token = "$(openssl rand -base64 32)"
EOF
fi

# Stand-in for /usr/local/bin/johnny: the Garage passthrough is all the panel needs.
cat >"$JOHNNY" <<EOF
#!/bin/sh
exec "$(command -v "$GARAGE_BIN")" -c "$STATE/garage.toml" "\$@"
EOF
chmod +x "$JOHNNY"

if ! is_running "$STATE/garage.pid"; then
  log "Starting Garage (S3 on 127.0.0.1:$S3_PORT)"
  nohup "$GARAGE_BIN" -c "$STATE/garage.toml" server >"$STATE/logs/garage.log" 2>&1 </dev/null &
  echo $! >"$STATE/garage.pid"
fi

for _ in $(seq 1 30); do
  "$JOHNNY" status >/dev/null 2>&1 && break
  sleep 0.5
done
STATUS="$("$JOHNNY" status)" || die "Garage did not start; see $STATE/logs/garage.log"

if grep -q "NO ROLE ASSIGNED" <<<"$STATUS"; then
  NODE_ID="$(awk '/^[0-9a-f]{16}/ {print $1; exit}' <<<"$STATUS")"
  log "Assigning single-node layout ($NODE_ID)"
  "$JOHNNY" layout assign -z dc1 -c 20G "$NODE_ID" >/dev/null
  "$JOHNNY" layout apply --version 1 >/dev/null
fi

# System keys and the protected default bucket, exactly like scripts/autoinstall.sh.
for key in johnny-default johnny-backup; do
  "$JOHNNY" key info "$key" >/dev/null 2>&1 || "$JOHNNY" key create "$key" >/dev/null
done
"$JOHNNY" bucket info default >/dev/null 2>&1 || "$JOHNNY" bucket create default >/dev/null
"$JOHNNY" bucket allow --read --write --owner default --key johnny-default >/dev/null
"$JOHNNY" bucket allow --read default --key johnny-backup >/dev/null

KEY_INFO="$("$JOHNNY" key info --show-secret johnny-default)"
ACCESS_KEY="$(awk -F': *' '/^Key ID:/ {print $2}' <<<"$KEY_INFO")"
SECRET_KEY="$(awk -F': *' '/^Secret key:/ {print $2}' <<<"$KEY_INFO")"
cat >"$STATE/credentials/default-s3.env" <<EOF
AWS_ACCESS_KEY_ID=$ACCESS_KEY
AWS_SECRET_ACCESS_KEY=$SECRET_KEY
AWS_DEFAULT_REGION=johnny
AWS_ENDPOINT_URL=$S3_URL
EOF

# --- Panel ------------------------------------------------------------------
if [[ ! -d "$PANEL_DIR/vendor" ]]; then
  log "Installing panel dependencies"
  composer install --no-interaction --working-dir="$PANEL_DIR" >/dev/null
fi

ENV_FILE="$PANEL_DIR/.env.demo"
APP_KEY_LINE="$(grep -s '^APP_KEY=base64:' "$ENV_FILE" || echo "APP_KEY=base64:$(openssl rand -base64 32)")"
cat >"$ENV_FILE" <<EOF
# Generated by demo/up.sh — used when APP_ENV=demo. Safe to delete.
APP_NAME="Johnny Panel"
APP_ENV=demo
$APP_KEY_LINE
APP_DEBUG=true
APP_URL=$PANEL_URL
APP_TIMEZONE=UTC

LOG_CHANNEL=single
DB_CONNECTION=sqlite
DB_DATABASE=$STATE/panel.sqlite
SESSION_DRIVER=file
CACHE_STORE=file
QUEUE_CONNECTION=sync
MAIL_MAILER=log

GARAGE_ACCESS_KEY_ID=$ACCESS_KEY
GARAGE_SECRET_ACCESS_KEY=$SECRET_KEY
GARAGE_DEFAULT_REGION=johnny
GARAGE_ENDPOINT=$S3_URL
GARAGE_DATA_DIR=$STATE/data

JOHNNY_CLI_BINARY=$JOHNNY
JOHNNY_CLI_SUDO_USER=
EOF

touch "$STATE/panel.sqlite"
artisan migrate --force >/dev/null
artisan johnny:admin "$DEMO_EMAIL" "$DEMO_PASSWORD" >/dev/null

if ! is_running "$STATE/panel.pid"; then
  log "Starting panel on $PANEL_URL"
  (
    cd "$PANEL_DIR"
    APP_ENV=demo nohup php artisan serve --host=127.0.0.1 --port="$PANEL_PORT" --no-reload \
      >"$STATE/logs/panel.log" 2>&1 </dev/null &
    echo $! >"$STATE/panel.pid"
  )
fi

for _ in $(seq 1 30); do
  curl -fsS -o /dev/null "$PANEL_URL/up" 2>/dev/null && break
  sleep 0.5
done
curl -fsS -o /dev/null "$PANEL_URL/up" || die "Panel did not start; see $STATE/logs/panel.log"

# --- Sample data (first run only) --------------------------------------------
if [[ ! -f "$STATE/.seeded" ]]; then
  bash "$DEMO_DIR/seed.sh"
  touch "$STATE/.seeded"
fi

cat <<EOF

  Johnny demo is up.

  Panel     $PANEL_URL
  Login     $DEMO_EMAIL / $DEMO_PASSWORD
  S3        $S3_URL  (credentials: $STATE/credentials/default-s3.env)
  CLI       $JOHNNY bucket list

  Screenshots: npm --prefix demo install && node demo/screenshots.mjs
  Stop:        bash demo/down.sh   (add --wipe to delete all demo data)

EOF
